def plot_protein_coverage(
    fasta_df: pd.DataFrame,
    peptide_df: pd.DataFrame,
    metadata_df: pd.DataFrame,
    protein_id: str,
    grouping: str,
    selected_groups: list[str] = None,
    aggregation_method: AggregationMethod = AggregationMethod.median,
) -> dict[str, list[go.Figure]]:
    """
    Plots the coverage of a protein sequence by peptides. The resulting plot is divided into subplots for each group
    specified in the metadata dataframe. Each subplot shows the coverage of the protein sequence by peptides for
    samples in the group. The coverage is shown as a bar plot, with the height of each bar representing the number of
    peptides that cover that position in the protein sequence. Above the bar plot, the peptides are shown as rectangles,
    with the color of the rectangle representing the intensity of the peptide. The intensity is normalized
    between 0 and 1 for each group.

    :param fasta_df: DataFrame containing the protein sequences and their protein ids
    :param peptide_df: DataFrame containing the peptide sequences and their intensities
    :param metadata_df: DataFrame containing the sample metadata
    :param protein_id: The protein id to plot the coverage for
    :param grouping: The column in the metadata dataframe to group the samples by
    :param selected_groups: The groups to plot the coverage for, e.g. specific samples or treatment conditions
    :param aggregation_method: The method to aggregate peptide intensities when multiple peptides map to the same
    sequence

    :return: A dictionary containing the plotly figure for the protein coverage plot
    """
    if selected_groups is None or selected_groups == []:
        raise ValueError("No samples provided.")

    # add group information to the peptide dataframe
    peptide_df = peptide_df.merge(metadata_df, on="Sample")

    reduced_peptide_df = peptide_df[peptide_df[grouping].isin(selected_groups)].fillna(
        0
    )
    if len(reduced_peptide_df) == 0:
        raise ValueError("No peptides found for the samples provided.")

    protein_sequence_dict = dict(
        zip(fasta_df["Protein ID"], fasta_df["Protein Sequence"])
    )
    sequence_kmer_dict = build_kmer_dictionary(protein_sequence_dict)

    if len(sequence_kmer_dict) == 0:
        raise ValueError("K-mer dictionary is empty. Is the FASTA file valid?")
    if protein_id not in protein_sequence_dict:
        raise ValueError(f"Protein ID {protein_id} not found in protein dictionary.")

    protein_sequence = protein_sequence_dict[protein_id]
    peptide_matches = []
    coverage_by_group_name = {
        sample: [0] * len(protein_sequence) for sample in selected_groups
    }

    intensity_column = default_intensity_column(reduced_peptide_df)
    for (group_name, peptide_sequence), row in tqdm(
        reduced_peptide_df[[grouping, "Sequence", intensity_column]]
        .drop_duplicates()
        .groupby([grouping, "Sequence"]),
        desc="Matching peptides to protein",
        unit_scale=True,
        unit="peptide",
    ):
        sample = extract_peptide_from_slice(row, aggregation_method)
        if sample.empty:
            continue
        intensity = sample[intensity_column].values[0]
        protein_hits = match_peptide_to_protein_ids(
            peptide_sequence=peptide_sequence,
            protein_kmer_dictionary=sequence_kmer_dict,
            protein_dictionary=protein_sequence_dict,
        )
        # we only care about the hits pertaining to the argument-supplied protein id
        filtered_protein_hits = filter(
            lambda x: x.protein_id == protein_id, protein_hits
        )
        for protein_hit in filtered_protein_hits:
            # add the peptide sequence and location to the peptide matches pertaining to the protein id
            peptide_matches.append(
                PeptideMatch(
                    peptide_sequence=peptide_sequence,
                    start_location_on_protein=protein_hit.start_location_on_protein,
                    end_location_on_protein=protein_hit.end_location_on_protein,
                    intensity=log2(intensity),
                    metadata_group=group_name,
                )
            )
            # update the coverage of the protein sequence
            increment_coverage_inplace(coverage_by_group_name[group_name], protein_hit)

    if len(peptide_matches) == 0:
        raise ValueError(f"No peptides matched for protein {protein_id}")

    # now that all the matches have been determined with their start and end on the protein sequence, we need to find
    # an optimal solution for the location of their rectangles in the plot without overlap while minimizing the
    # required number of rows (vertical space)
    rows_by_group_name = distribute_to_rows(peptide_matches)

    figures = build_coverage_plot(
        coverages_by_group_name=coverage_by_group_name,
        protein_sequence=protein_sequence,
        rows_by_group_name=rows_by_group_name,
        grouping=grouping,
        aggregation_method=aggregation_method,
    )

    return {"plots": figures}


