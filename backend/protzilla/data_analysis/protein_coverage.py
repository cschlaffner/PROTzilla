def build_coverage_plot(
    coverages_by_group_name: dict[str, list[int]],
    protein_sequence: str,
    rows_by_group_name: dict[str, list[list[PeptideMatch]]],
    grouping: str = "",
    aggregation_method: AggregationMethod = AggregationMethod.median,
) -> list[go.Figure]:
    """
    Creates separate plotly figures showing the coverage of a protein sequence by peptides for each group.

    :param coverages_by_group_name: A dictionary mapping group names to coverage lists (i.e., lists that show how many
    peptides cover each position in the protein sequence)
    :param protein_sequence: The protein sequence to plot the coverage for
    :param rows_by_group_name: A dictionary mapping group names to lists of peptide match rows
    :param grouping: The column in the metadata dataframe to group the samples by
    :param aggregation_method: The method to aggregate peptide intensities when multiple peptides map to the same
    sequence

    :return: A list of plotly figures, one for each group, showing the coverage of the protein sequence by peptides
    """

    protein_sequence_labels = [
        f"{amino_acid} - {amino_acid_index} "
        for amino_acid_index, amino_acid in enumerate(protein_sequence)
    ]
    max_coverage_value = get_max_coverage(coverages_by_group_name)

    figures = []

    # Create a separate figure for each group
    for group_name in rows_by_group_name.keys():
        peptide_rows = rows_by_group_name[group_name]
        coverage = coverages_by_group_name[group_name]

        # Create a new figure for this group
        fig = go.Figure()

        # Calculate the desired heights
        max_bar_height = max_coverage_value
        desired_peptide_height = max_bar_height * 2  # 1:2 ratio

        # Calculate the height scaling factor for peptides
        num_peptide_rows = len(peptide_rows)
        if num_peptide_rows > 0:
            # Include spacing in the calculation
            total_spacing = SEQUENCE_DEPTH_PEPTIDE_SPACING
            peptide_box_height = (
                desired_peptide_height - total_spacing
            ) / num_peptide_rows
        else:
            peptide_box_height = 1.0

        add_sequence_depth_to_plot(
            fig=fig,
            coverage=coverage,
            protein_sequence_labels=protein_sequence_labels,
        )

        # Peptide plot
        # Checking for -inf because these are the result of log-transforming 0 intensities, i.e., peptides that were
        # identified but not quantified. We want to plot them but assign them a default color as not to distort the
        # color scale for actual intensity values.
        current_group_intensities = [
            peptide_match.intensity
            for row in peptide_rows
            for peptide_match in row
            if peptide_match.intensity > -np.inf
        ]
        max_intensity = max(current_group_intensities)
        min_intensity = min(current_group_intensities)

        def scale_intensity(intensity):
            if intensity == -np.inf:
                return np.nan
            if max_intensity != min_intensity:
                return (intensity - min_intensity) / (max_intensity - min_intensity)
            return 0

        for row_index, row in enumerate(peptide_rows):
            for peptide_match in row:
                add_peptide_to_plot(
                    fig=fig,
                    normalized_intensity=scale_intensity(peptide_match.intensity),
                    peptide_match=peptide_match,
                    protein_sequence_labels=protein_sequence_labels,
                    row_index=row_index,
                    offset=max_coverage_value + SEQUENCE_DEPTH_PEPTIDE_SPACING,
                    box_height=peptide_box_height,
                    grouping=grouping,
                )

        # Update y-axis range to accommodate both the bar plot and peptide sections
        total_height = (
            max_coverage_value + SEQUENCE_DEPTH_PEPTIDE_SPACING + desired_peptide_height
        )

        fig.update_layout(
            title=f"Peptides of {group_name}",
            hovermode="closest",
            showlegend=False,
        )
        fig.update_yaxes(
            range=[0, total_height],
            showticklabels=False,
            showgrid=False,
        )
        fig.update_xaxes(showticklabels=True, showgrid=False)

        add_intensity_legend(fig, aggregation_method)

        figures.append(fig)

    return figures


def add_intensity_legend(
    fig: go.Figure, aggregation_method: AggregationMethod = AggregationMethod.median
):
    """
    Adds a color legend to the plotly figure indicating the intensity scale used for the peptides.

    :param fig: The plotly figure to add the legend to
    :param aggregation_method: The method used to aggregate peptide intensities
    """
    color_legend_trace = go.Scatter(
        x=[None],
        y=[None],
        mode="markers",
        marker={
            "colorscale": INTENSITY_COLOR_SCALE,
            "showscale": True,
            "cmin": 0,
            "cmax": 1,
            "colorbar": {
                "title": f"Relative intensity of peptide<br>(aggregated via {aggregation_method})",
                "x": 1.0,
                "len": 0.9,
                "thickness": 30,
                "title_side": "right",
            },
            "size": 10,
        },
        showlegend=False,
    )
    fig.add_trace(color_legend_trace)


def add_sequence_depth_to_plot(
    fig: go.Figure,
    coverage: list[int],
    protein_sequence_labels: list[str],
) -> None:
    """
    Adds a bar chart to the plotly figure indicating the sequencing depth at each position in the protein sequence.

    :param fig: The plotly figure to add the bar chart to
    :param coverage: A list indicating the sequencing depth at each position in the protein sequence
    :param protein_sequence_labels: A list of labels for the x-axis of the bar chart
    """
    sequence_depth_bar_chart = {
        "x": protein_sequence_labels,
        "y": coverage,
        "showlegend": False,
        "marker": {"color": PLOT_PRIMARY_COLOR},
        "hoverinfo": "y",
        "hovertemplate": "Sequencing depth at %{x}: %{y}",
    }
    fig.add_trace(go.Bar(**sequence_depth_bar_chart))


def add_peptide_to_plot(
    fig: go.Figure,
    normalized_intensity: float,
    peptide_match: PeptideMatch,
    protein_sequence_labels: list[str],
    row_index: int,
    offset: int,
    box_height: float,
    grouping: str = "",
) -> None:
    """
    Adds a rectangle to the plotly figure indicating the position of a peptide on the protein sequence.

    :param fig: The plotly figure to add the rectangle to
    :param normalized_intensity: The normalized intensity of the peptide (between 0 and 1)
    :param peptide_match: The PeptideMatch object containing the peptide sequence and its position on the protein
    :param protein_sequence_labels: A list of labels for the x-axis of the rectangle
    :param row_index: The index of the row to add the rectangle to
    :param offset: The offset to add to the y-axis position of the rectangle
    :param box_height: The height of the rectangle
    :param color_a: The color to use for the lowest intensity
    :param color_b: The color to use for the highest intensity
    :param grouping: The column in the metadata dataframe to group the samples by
    """
    x0, x1 = (
        peptide_match.start_location_on_protein,
        peptide_match.end_location_on_protein,
    )
    y0, y1 = row_index * box_height + offset, (row_index + 1) * box_height + offset
    # interpolate between the two colors
    color = (
        plotly.colors.sample_colorscale(INTENSITY_COLOR_SCALE, normalized_intensity)[0]
        if not np.isnan(normalized_intensity)
        else "#CCCCCC"
    )
    peptide_shape = {
        "type": "rect",
        "x0": x0 - 0.5,
        "y0": y0,
        "x1": x1 - 0.5,
        "y1": y1,
        "fillcolor": color,
        "line_color": color,
        "layer": "above",
    }
    fig.add_shape(**peptide_shape)
    # add invisible plotly object to the rectangle to show the peptide sequence when hovered over
    fig.add_trace(
        go.Scatter(
            x=protein_sequence_labels[
                peptide_match.start_location_on_protein : peptide_match.end_location_on_protein
                + 1
            ],
            y=[(y0 + y1) / 2] * len(peptide_match.peptide_sequence),
            text=[
                f"{grouping}: {peptide_match.metadata_group}<br>Peptide: {peptide_match.peptide_sequence}<br>"
                f"({peptide_match.start_location_on_protein}-{peptide_match.end_location_on_protein})<br>"
                f"Log2 Intensity: {peptide_match.intensity}"
            ]
            * len(peptide_match.peptide_sequence),
            mode="markers",
            marker={"opacity": 0, "size": 15},  # make marker invisible
            hoverinfo="text",
            hovertemplate="%{text}<extra></extra>",
            showlegend=False,
        ),
    )


def increment_coverage_inplace(coverage: list[int], protein_hit: ProteinHit) -> None:
    """
    Increments the coverage of a protein sequence by 1 for each position covered by the given protein hit.

    :param coverage: A list indicating the sequencing depth at each position in the protein sequence
    :param protein_hit: The ProteinHit object containing the start and end location of the peptide on the protein
    """
    start, end = (
        protein_hit.start_location_on_protein,
        protein_hit.end_location_on_protein,
    )
    coverage[start:end] = [value + 1 for value in coverage[start:end]]


def extract_peptide_from_slice(
    slice_df: pd.DataFrame,
    aggregation_strategy: AggregationMethod = AggregationMethod.median,
) -> pd.DataFrame:
    """
    Given multiple peptide datapoints, return a single peptide datapoint with the intensity value extracted from the
    slice of the peptide data.

    :param slice_df: A DataFrame containing multiple peptide datapoints for the same peptide sequence
    :param aggregation_strategy: The method to aggregate peptide intensities when multiple peptides map to the same
    sequence
    """
    if len(slice_df) == 1:
        return slice_df
    if aggregation_strategy == AggregationMethod.median:
        slice_df = slice_df.groupby("Sequence").median(numeric_only=True)
    elif aggregation_strategy == AggregationMethod.mean:
        slice_df = slice_df.groupby("Sequence").mean(numeric_only=True)
    else:
        raise ValueError(f"Unknown strategy: {aggregation_strategy}")
    return slice_df


def distribute_to_rows(
    peptide_matches: list[PeptideMatch],
) -> dict[str, list[list[PeptideMatch]]]:
    """
    Distributes peptide matches to rows such that no two peptides overlap in the same row.
    Greedy algorithm (see Interval Scheduling Problem).

    :param peptide_matches: A list of PeptideMatch objects to distribute to rows
    """
    if len(peptide_matches) == 0:
        raise ValueError(
            "Attempted to distribute empty list of peptide matches to rows in plot."
        )
    peptide_matches.sort(
        key=lambda peptide_match: peptide_match.start_location_on_protein
    )
    rows = {
        group_name: []
        for group_name in {
            peptide_match.metadata_group for peptide_match in peptide_matches
        }
    }
    for peptide_match in peptide_matches:
        # find the first row that does not overlap with the current peptide
        for row in rows[peptide_match.metadata_group]:
            if (
                row[-1].end_location_on_protein
                < peptide_match.start_location_on_protein
            ):
                row.append((peptide_match))
                break
        else:
            rows[peptide_match.metadata_group].append([peptide_match])
    return rows


def get_max_coverage(coverage: dict[str, list[int]]) -> int:
    """
    Gets the maximum coverage value from a dictionary of coverage lists.

    :param coverage: A dictionary mapping group names to coverage lists (i.e., lists that show how many peptides cover
    each position in the protein sequence)

    :return: The maximum coverage value across all groups
    """
    if len(coverage) == 0:
        raise ValueError(
            "Cannot calculate maximum coverage value: No coverage data provided."
        )
    return max(max(coverage) for coverage in coverage.values())
