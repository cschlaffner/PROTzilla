import numpy as np
import pandas as pd
import plotly.colors
import plotly.graph_objects as go
from dataclasses import dataclass
from enum import StrEnum
from numpy import log2
from tqdm import tqdm

from backend.protzilla.constants.colors import PLOT_PRIMARY_COLOR
from backend.protzilla.utilities.utilities import default_intensity_column

INTENSITY_COLOR_SCALE = plotly.colors.sequential.Cividis
SEQUENCE_DEPTH_PEPTIDE_SPACING = 1


class IntensityNormalization(StrEnum):
    min_max_scaling = "min_max_scaling"
    none = "none"


class AggregationMethod(StrEnum):
    median = "median"
    mean = "mean"


@dataclass(unsafe_hash=True)
class PeptideMatch:
    peptide_sequence: str
    start_location_on_protein: int
    end_location_on_protein: int
    intensity: float = 0.0
    metadata_group: str = ""


@dataclass(unsafe_hash=True)
class ProteinHit:
    protein_id: str
    start_location_on_protein: int
    end_location_on_protein: int


def build_kmer_dictionary(
    protein_dictionary: dict[str, str], k: int = 5
) -> dict[str, list[tuple[str, int]]]:
    """
    Builds a dictionary of all kmers in a list of protein sequences. The kmers are generated by sliding a window of size
    k along the protein sequences. The dictionary maps the k-mer to a list of tuples containing the protein ID and
    the index of the k-mer in the protein sequence.

    :param protein_dictionary: A dictionary mapping protein IDs to protein sequences.
    :param k: The size of the k-mers to generate.

    :return: A dictionary mapping k-mers to a list of tuples containing the protein ID and the index of the k-mer in the
    protein sequence.
    """
    # if the dictionary already exists, load it from disk
    kmer_dict = {}
    for protein_id, protein_sequence in tqdm(
        protein_dictionary.items(),
        desc="Building kmer dictionary",
        unit_scale=True,
        unit="protein",
    ):
        for i in range(len(protein_sequence) - k + 1):
            kmer = protein_sequence[i : i + k]
            if kmer in kmer_dict:
                kmer_dict[kmer].append((protein_id, i))
            else:
                kmer_dict[kmer] = [(protein_id, i)]
    return kmer_dict


def match_peptide_to_protein_ids(
    peptide_sequence: str,
    protein_kmer_dictionary: dict[str, list[tuple[str, int]]],
    protein_dictionary: dict[str, str],
) -> list[ProteinHit]:
    """
    Matches a peptide sequence to a dictionary of kmers in protein sequences.

    :param peptide_sequence: The peptide sequence to match.
    :param protein_kmer_dictionary: A dictionary mapping k-mers to a list of tuples containing the protein ID and the
    index of the k-mer in the protein sequence.
    :param protein_dictionary: A dictionary mapping protein IDs to protein sequences.

    :return: A list of ProteinHit objects containing the protein ID and the start location of the peptide on the
    protein.
    """
    if len(peptide_sequence) == 0:
        raise ValueError("Peptide sequence is empty.")
    # infer k from the kmer dictionary
    k = len(list(protein_kmer_dictionary.keys())[0])
    peptide_kmers = [
        peptide_sequence[i : i + k] for i in range(len(peptide_sequence) - k + 1)
    ]
    first_kmer, last_kmer = peptide_kmers[0], peptide_kmers[-1]
    # match the kmers
    first_kmer_matches = protein_kmer_dictionary.get(first_kmer, [])
    last_kmer_matches = protein_kmer_dictionary.get(last_kmer, [])
    if first_kmer_matches == [] or last_kmer_matches == []:
        return []

    hits = []
    for protein_id_a, start_first_kmer in first_kmer_matches:
        for protein_id_b, start_last_kmer in last_kmer_matches:
            if protein_id_a != protein_id_b:
                continue
            expected_last_start = start_first_kmer + len(peptide_sequence) - k
            if start_last_kmer != expected_last_start:
                continue
            start = start_first_kmer
            end = start_first_kmer + len(peptide_sequence)
            if protein_dictionary[protein_id_a][start:end] == peptide_sequence:
                hits.append(ProteinHit(protein_id_a, start, end))
    hits = list(set(hits))

    # Sanity checks
    for hit in hits:
        subsequence = protein_dictionary[hit.protein_id][
            hit.start_location_on_protein : hit.end_location_on_protein
        ]
        assert len(subsequence) == len(
            peptide_sequence
        ), f"Lengths do not match: {len(subsequence)} != {len(peptide_sequence)}"
        assert (
            subsequence in peptide_sequence
        ), f"Subsequence not in peptide sequence:\nA: {subsequence}\nB: {peptide_sequence}"
        assert (
            peptide_sequence in protein_dictionary[hit.protein_id]
        ), f"Peptide not in protein sequence: {peptide_sequence} not in {protein_dictionary[hit.protein_id]}"
    return hits


